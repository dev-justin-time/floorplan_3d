/**
 * Copies the browser runtime dependencies into vendor/ so the site does not
 * load anything from a third-party CDN.
 *
 * The import maps in pages/ point at these files:
 *
 *   three                  -> /vendor/three/three.module.js
 *   three/addons/          -> /vendor/three/addons/
 *   three/nodes            -> /vendor/three/addons/nodes/Nodes.js
 *   three-bvh-csg          -> /vendor/three-bvh-csg/index.module.js
 *   three-mesh-bvh         -> /vendor/three-mesh-bvh/index.module.js
 *
 * Only the addons the project actually imports are copied, plus every file
 * those addons pull in relatively, which keeps the tree at ~1 MB instead of the
 * whole examples/jsm folder. Run `node scripts/vendor-deps.mjs` after upgrading
 * a dependency; the output is deterministic.
 */
import { readFile, readdir, mkdir, copyFile, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NODE_MODULES = path.join(ROOT, 'node_modules');
const VENDOR = path.join(ROOT, 'vendor');
const THREE_JSM = path.join(NODE_MODULES, 'three', 'examples', 'jsm');

const norm = (file) => file.split(path.sep).join('/');

async function walk(dir, out = []) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        if (['node_modules', '.git', 'vendor', '.freebuff'].includes(entry.name)) continue;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) await walk(full, out);
        else out.push(full);
    }
    return out;
}

async function packageVersion(name) {
    const file = path.join(NODE_MODULES, name, 'package.json');
    if (!existsSync(file)) return null;
    return JSON.parse(await readFile(file, 'utf8')).version;
}

async function copy(from, to) {
    await mkdir(path.dirname(to), { recursive: true });
    await copyFile(from, to);
}

/* 1. Which addons does the site import? */
const projectFiles = (await walk(ROOT)).filter((file) => /\.(js|mjs|html)$/.test(file));
const roots = new Set();
for (const file of projectFiles) {
    const text = await readFile(file, 'utf8');
    for (const match of text.matchAll(/three\/addons\/([A-Za-z0-9/_.-]+\.js)/g)) roots.add(match[1]);
}
if (!roots.size) throw new Error('no three/addons imports found — nothing to vendor');

/* 2. Follow relative imports inside the addon tree. */
const closure = new Set();
const queue = [...roots].map((rel) => path.join(THREE_JSM, rel));
const bare = new Set();
while (queue.length) {
    const file = queue.pop();
    if (closure.has(file)) continue;
    if (!existsSync(file)) {
        console.warn(`  missing addon: ${norm(path.relative(ROOT, file))}`);
        continue;
    }
    closure.add(file);
    const text = await readFile(file, 'utf8');
    for (const match of text.matchAll(/^\s*(?:import|export)[\s\S]*?from\s*['"]([^'"]+)['"]/gm)) {
        const spec = match[1];
        if (spec.includes('...')) continue; // doc-comment placeholder
        if (spec.startsWith('.')) queue.push(path.resolve(path.dirname(file), spec));
        else if (spec.startsWith('three/addons/')) queue.push(path.join(THREE_JSM, spec.slice('three/addons/'.length)));
        else if (spec !== 'three') bare.add(spec);
    }
}

let copied = 0;
let bytes = 0;
const measure = async (file) => { bytes += (await stat(file)).size; copied += 1; };

for (const file of closure) {
    const rel = path.relative(THREE_JSM, file);
    const to = path.join(VENDOR, 'three', 'addons', rel);
    await copy(file, to);
    await measure(file);
}
await copy(path.join(NODE_MODULES, 'three', 'build', 'three.module.js'), path.join(VENDOR, 'three', 'three.module.js'));
await measure(path.join(NODE_MODULES, 'three', 'build', 'three.module.js'));

/* 3. The support packages the import maps name. */
const packages = [
    ['three-bvh-csg', 'build/index.module.js', 'index.module.js'],
    ['three-mesh-bvh', 'build/index.module.js', 'index.module.js'],
    ['nipplejs', 'dist/nipplejs.js', 'nipplejs.js'],
    ['nipplejs', 'LICENSE', 'LICENSE']
];
for (const [name, from, to] of packages) {
    const source = path.join(NODE_MODULES, name, from);
    if (!existsSync(source)) {
        console.warn(`  missing package file: ${name}/${from}`);
        continue;
    }
    await copy(source, path.join(VENDOR, name, to));
    await measure(source);
}

/* 4. Record what is vendored, so an upgrade is visible in review. */
const versions = {};
for (const name of ['three', 'three-bvh-csg', 'three-mesh-bvh', 'nipplejs']) {
    versions[name] = await packageVersion(name);
}
const readme = [
    '# Vendored browser dependencies',
    '',
    'Generated by `node scripts/vendor-deps.mjs` — do not edit by hand.',
    '',
    '| Package | Version |',
    '| --- | --- |',
    ...Object.entries(versions).map(([name, version]) => `| ${name} | ${version ?? 'unknown'} |`),
    '',
    'The pages resolve `three`, `three/addons/`, `three/nodes`, `three-bvh-csg`,',
    '`three-mesh-bvh` and `nipplejs` to these files through the import maps in',
    '`pages/*.html`. Keeping the closure here means a production deploy needs no',
    '`npm install` and the site makes no third-party runtime request.',
    ''
].join('\n');
await writeFile(path.join(VENDOR, 'README.md'), readme);

console.log(`vendored ${copied} files, ${(bytes / 1048576).toFixed(2)} MB -> vendor/`);
if (bare.size) console.log(`bare specifiers needing an import-map entry: ${[...bare].sort().join(', ')}`);
else console.log('no unmapped bare specifiers inside the addon closure');
