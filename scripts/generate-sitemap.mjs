/**
 * Writes `sitemap.xml`, points robots.txt at it, and gives every page an
 * absolute `<link rel="canonical">` and `<meta property="og:url">`.
 *
 * A sitemap needs absolute URLs, and the origin lives in exactly one place
 * (scripts/site-origin.mjs), so the head tags and the sitemap are generated
 * rather than hand-maintained in 28 files. The output is deterministic: running
 * this twice leaves the tree unchanged, which is what the gate relies on —
 * `check-pages` asserts the committed values match the origin, and CI re-runs
 * this script and fails on a diff, so a stale origin or an added page cannot
 * slip through.
 *
 * The root `index.html` is not a destination: it only redirects, so it points
 * its canonical at the landing page and is left out of the sitemap.
 *
 * Usage: node scripts/generate-sitemap.mjs        (write)
 *        node scripts/generate-sitemap.mjs --check (exit 1 on any difference)
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANDING_PAGE, SITE_ORIGIN, SITEMAP_URL, pageUrl } from './site-origin.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

const DESCRIPTION = /^([ \t]*)<meta\s+name=["']description["'][^>]*>\r?\n/im;
const OG_DESCRIPTION = /^([ \t]*)<meta\s+property=["']og:description["'][^>]*>\r?\n/im;
const TITLE = /^([ \t]*)<title>[^<]*<\/title>\r?\n/im;
const CANONICAL = /<link\b[^>]*\brel=["']canonical["'][^>]*>/i;
const OG_URL = /<meta\b[^>]*\bproperty=["']og:url["'][^>]*>/i;

/** Insert `snippet` on its own line after the first line matching `anchor`. */
function insertAfter(html, anchor, snippet, eol) {
    const match = anchor.exec(html);
    if (!match) return null;
    const at = match.index + match[0].length;
    return html.slice(0, at) + `${match[1]}${snippet}${eol}` + html.slice(at);
}

/** Set (or add) one head tag, keeping the file's own line endings. */
function upsert(html, pattern, anchor, tag, eol) {
    if (pattern.test(html)) return html.replace(pattern, tag);
    const next = insertAfter(html, anchor, tag, eol)
        ?? insertAfter(html, TITLE, tag, eol);
    if (next == null) throw new Error('no description, og:description or title to anchor on');
    return next;
}

async function renderPage(file, relative) {
    const html = await readFile(file, 'utf8');
    const eol = html.includes('\r\n') ? '\r\n' : '\n';
    const url = pageUrl(relative);

    let out = upsert(html, CANONICAL, DESCRIPTION, `<link rel="canonical" href="${url}">`, eol);
    out = upsert(out, OG_URL, OG_DESCRIPTION, `<meta property="og:url" content="${url}">`, eol);
    return { out, changed: out !== html };
}

async function renderRootRedirect() {
    const file = path.join(ROOT, 'index.html');
    const html = await readFile(file, 'utf8');
    const eol = html.includes('\r\n') ? '\r\n' : '\n';
    // It has no Open Graph metadata of its own; the canonical names where the
    // redirect actually lands.
    const tag = `<link rel="canonical" href="${pageUrl(LANDING_PAGE)}">`;
    const out = CANONICAL.test(html)
        ? html.replace(CANONICAL, tag)
        : insertAfter(html, TITLE, tag, eol);
    return { file, out: out ?? html, changed: out !== html };
}

function renderSitemap(routes) {
    const urls = routes
        .map((route) => `    <url><loc>${pageUrl(route)}</loc></url>`)
        .join('\n');
    return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by scripts/generate-sitemap.mjs from scripts/site-origin.mjs. -->',
        '<!-- Regenerate instead of editing: the page gate compares both against the origin. -->',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        urls,
        '</urlset>',
        ''
    ].join('\n');
}

function renderRobots() {
    // robots.txt is four lines that only change with the origin, so it is
    // rendered whole rather than patched: no chance of two Sitemap lines.
    return [
        '# Floorplan 3D — static site, everything is public.',
        '# Generated by scripts/generate-sitemap.mjs: the Sitemap line follows SITE_ORIGIN.',
        'User-agent: *',
        'Allow: /',
        '',
        `Sitemap: ${SITEMAP_URL}`,
        ''
    ].join('\n');
}

const pagesDir = path.join(ROOT, 'pages');
const routes = (await readdir(pagesDir))
    .filter((name) => name.endsWith('.html'))
    .sort((a, b) => a.localeCompare(b))
    .map((name) => `pages/${name}`);

const edits = [];
for (const route of routes) {
    const { out, changed } = await renderPage(path.join(ROOT, route), route);
    edits.push({ file: route, out, changed });
}
const root = await renderRootRedirect();
edits.push({ file: 'index.html', out: root.out, changed: root.changed });

const sitemapFile = path.join(ROOT, 'sitemap.xml');
const robotsFile = path.join(ROOT, 'robots.txt');
const sitemap = renderSitemap(routes);
const robots = renderRobots();

const sitemapChanged = (await readFile(sitemapFile, 'utf8').catch(() => null)) !== sitemap;
const robotsChanged = (await readFile(robotsFile, 'utf8').catch(() => null)) !== robots;

const changed = [
    ...edits.filter((entry) => entry.changed).map((entry) => entry.file),
    ...(sitemapChanged ? ['sitemap.xml'] : []),
    ...(robotsChanged ? ['robots.txt'] : [])
];

if (CHECK_ONLY) {
    if (changed.length) {
        console.log(`FAIL ${changed.length} file(s) out of date with ${SITE_ORIGIN}:`);
        for (const file of changed) console.log(`       ${file}`);
        console.log('       run: node scripts/generate-sitemap.mjs');
        process.exitCode = 1;
    } else {
        console.log(`ok   ${routes.length} pages, sitemap.xml and robots.txt match ${SITE_ORIGIN}`);
    }
} else {
    for (const entry of edits) {
        if (entry.changed) await writeFile(path.join(ROOT, entry.file), entry.out);
    }
    if (sitemapChanged) await writeFile(sitemapFile, sitemap);
    if (robotsChanged) await writeFile(robotsFile, robots);
    console.log(`sitemap: ${routes.length} pages under ${SITE_ORIGIN}`);
    console.log(changed.length ? `written: ${changed.join(', ')}` : 'already up to date');
}
