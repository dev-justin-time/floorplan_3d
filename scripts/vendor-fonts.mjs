/**
 * Downloads the Google Fonts the pages use and writes them to assets/fonts/.
 *
 * The pages load three families: Space Grotesk (display), Inter (calculator)
 * and Material Symbols Outlined (icons). Serving them from fonts.googleapis.com
 * makes every route depend on a third party at runtime, so this script fetches
 * the CSS once with a browser user agent (which is what returns woff2 URLs),
 * downloads each face, and rewrites the src urls to the local copies.
 *
 * Run `node scripts/vendor-fonts.mjs` to refresh. Then the pages link
 * assets/fonts/fonts.css and make no request to Google.
 */
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'assets', 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const SOURCES = [
    'https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@300..700&display=swap',
    'https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700&display=swap',
    'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=Space+Grotesk:wght@500;700&display=swap',
    'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined'
];

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

async function fetchText(url, binary = false) {
    const response = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!response.ok) throw new Error(`${url} -> ${response.status}`);
    return binary ? Buffer.from(await response.arrayBuffer()) : response.text();
}

await mkdir(OUT, { recursive: true });

const files = new Map(); // remote url -> local name
const blocks = new Map(); // dedupe identical @font-face blocks across the two Inter calls
let bytes = 0;

for (const source of SOURCES) {
    const css = await fetchText(source);
    for (const match of css.matchAll(/@font-face\s*{([\s\S]*?)}/g)) {
        const body = match[1];
        const family = /font-family:\s*'(?:[^']+)'/.exec(body)?.[0] || '';
        const weights = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim() || '';
        const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim() || '';
        const remote = /url\((https:\/\/[^)]+\.woff2)\)/.exec(body)?.[1];
        if (!remote) continue;

        if (!files.has(remote)) {
            const name = `${slug(family.replace(/font-family:\s*'|'/g, ''))}-${createHash('sha1').update(remote).digest('hex').slice(0, 10)}.woff2`;
            const data = await fetchText(remote, true);
            await writeFile(path.join(OUT, name), data);
            bytes += data.length;
            files.set(remote, name);
            console.log(`  ${name} (${(data.length / 1024).toFixed(0)} KB)`);
        }

        const local = `./${files.get(remote)}`;
        const rewritten = body
            .replace(/url\(https:\/\/[^)]+\.woff2\)/g, `url('${local}')`)
            .trim();
        blocks.set(`${family}|${weights}|${range}|${local}`, rewritten);
    }
}

const css = [
    '/* Self-hosted Google Fonts. Generated by scripts/vendor-fonts.mjs. */',
    ...[...blocks.values()].map((body) => `@font-face {\n${body}\n}`)
].join('\n\n');
await writeFile(path.join(OUT, 'fonts.css'), `${css}\n`);

console.log(`\n${files.size} font files, ${(bytes / 1024).toFixed(0)} KB, ${blocks.size} faces -> assets/fonts/`);
